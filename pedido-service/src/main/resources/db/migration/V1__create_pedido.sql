CREATE TABLE pedido (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id INTEGER        NOT NULL,
    cantidad    INTEGER        NOT NULL,
    total       NUMERIC(14, 2) NOT NULL,
    CONSTRAINT chk_pedido_cantidad_positiva CHECK (cantidad > 0),
    CONSTRAINT chk_pedido_total_nover       CHECK (total >= 0)
);

CREATE INDEX idx_pedido_producto ON pedido (producto_id);
